const makeArcana = ({
  id,
  name,
  icon,
  element,
  styleTags,
  description,
  summary,
  rows,
  chain,
  uiColor,
  uiBorder,
  uiBackground,
}) => Object.freeze({
  id:`WOL-${id}`,
  arcanaId:id,
  sourceGame:'Wizard of Legend',
  type:'ability',
  name,
  icon,
  element,
  playEvent:'wizard-arcana:play',
  description,
  details:Object.freeze({
    summary,
    rows:Object.freeze(rows.map(row=>Object.freeze(row.slice()))),
  }),
  chain:Object.freeze(chain),
  preferredWeapons:Object.freeze(['any']),
  styleTags:Object.freeze(['Wizard Arcana',element,...styleTags]),
  uiColor,
  uiBorder,
  uiBackground,
});

