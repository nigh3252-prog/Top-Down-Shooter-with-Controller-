function makeCard({id,name,icon,element,category,sourceOrder,clip,styleTags,description,summary,rows,chain,baseForm,dashMotion}){
  const colors=palette[element];
  return deepFreeze({
    id:`WOL-${id}`,
    arcanaId:id,
    sourceGame:'Wizard of Legend',
    sourceOrder,
    sourceCategory:category,
    sourceClip:{start:clip[0],end:clip[1]},
    baseFormOnly:true,
    baseForm,
    ...(dashMotion?{dashMotion}:{}),
    type:'ability',
    name,
    icon,
    element,
    playEvent:'wizard-arcana:play',
    description,
    details:{summary,rows},
    chain,
    preferredWeapons:['any'],
    styleTags:['Wizard Arcana',element,category,...styleTags],
    uiColor:colors.color,
    uiBorder:colors.border,
    uiBackground:colors.background,
  });
}

